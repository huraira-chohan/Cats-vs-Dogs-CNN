from tensorflow.keras.preprocessing.image import load_img, img_to_array

def predict(path):
    img = load_img(path, target_size=(224, 224))      # load n resize
    x = img_to_array(img) / 255.0                     # to array + normalize
    x = x.reshape(1, 224, 224, 3)                      # adding batch dimension

    p = model.predict(x, verbose=0)[0][0]              # getting the probability

    if p > 0.5:
        print(f"DOG → {p*100:.1f}%")
    else:
        print(f"CAT → {(1-p)*100:.1f}%")

