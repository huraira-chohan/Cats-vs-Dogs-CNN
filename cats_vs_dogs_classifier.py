from keras.src.backend import image
import tensorflow as tf
import numpy as np
from tensorflow.keras.preprocessing.image import ImageDataGenerator
import os
from PIL import Image

def remove_corrupt_images(base_dir='PetImages'):
    removed = 0
    for root, _, files in os.walk(base_dir):
        for file in files:
            if file.lower().endswith(('.jpg', '.jpeg', '.png')):
                path = os.path.join(root, file)
                try:
                    img = Image.open(path)
                    img.verify()
                except Exception:
                    print(f"Removing corrupt: {path}")
                    os.remove(path)
                    removed += 1
    print(f"Removed {removed} corrupt images.")

remove_corrupt_images()

data = ImageDataGenerator(
    rescale = 1./255, # this will only change the brightness of the pixel
    validation_split = 0.2
)

data = ImageDataGenerator(rescale=1./255,
                          validation_split=0.2)

train_generator = data.flow_from_directory(
    'PetImages',
    target_size=(224, 224), # this changes the size of the image
    batch_size=32,
    class_mode='binary',
    subset='training'
)


val_generator = data.flow_from_directory(
    'PetImages',
    target_size=(224, 224),
    batch_size=32,
    class_mode='binary',
    subset='validation'
)

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Conv2D, MaxPooling2D, Flatten, Dense, Dropout


model = Sequential([
    Conv2D(32,(3,3),activation='relu',input_shape=(224,224,3)),
    MaxPooling2D(2,2),

    Conv2D(64,(3,3),activation='relu'),
    MaxPooling2D(2,2),

    Conv2D(128,(3,3),activation='relu'),
    MaxPooling2D(2,2),

    Flatten(),
    Dense(512,activation='relu'),
    Dropout(0.4),
    Dense(1,activation='sigmoid')
])

model.summary()

model.compile(optimizer='adam',loss='binary_crossentropy',metrics=['accuracy'])

history = model.fit(train_generator,epochs=5,validation_data=val_generator)

import joblib
joblib.dump(model, 'cats-vs-dogs.pkl')

